"""Write the task list for the built-in-tools robustness check.

Picks N random pairs (both sides) per category from the pairs that already
have both sides graded in agentabstain_results/, so the re-run with Claude
Code's built-in tools switched off can be compared run by run.

With --rest, writes the complementary list instead: every other complete
pair, so the two lists together re-run all pairs.

Usage:
    python runs/make_check_config.py [--per-category 2] [--seed 0] [--rest]
"""

from __future__ import annotations

import argparse
import random
import sys
from collections import defaultdict
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "analysis"))

from cost_scoring import load_runs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--per-category", type=int, default=2)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--rest", action="store_true", help="write the pairs the check did not pick")
    args = parser.parse_args()

    runs, _, _ = load_runs(REPO / "agentabstain_results")
    sides: dict = defaultdict(set)
    for r in runs:
        sides[(r.category, r.task_id)].add(r.side)
    complete: dict = defaultdict(list)
    for (category, task_id), s in sorted(sides.items()):
        if s == {"act", "abstain"}:
            complete[category].append(task_id)

    rng = random.Random(args.seed)
    tasks = []
    for category in sorted(complete):
        picked = set(rng.sample(complete[category], args.per_category))
        chosen = [t for t in complete[category] if (t not in picked) == args.rest]
        for task_id in sorted(chosen):
            tasks += [{"category": category, "task_id": task_id, "task_type": s} for s in ("act", "abstain")]

    if args.rest:
        out = REPO / "runs" / "rerun_rest_no_builtin_tools.yaml"
        header = ("# Every complete pair the robustness check did not pick, re-run with Claude Code's\n"
                  f"# built-in tools switched off. Generated by runs/make_check_config.py --rest; {len(tasks)} runs.\n")
    else:
        out = REPO / "runs" / "check_no_builtin_tools.yaml"
        header = (f"# {args.per_category} random pairs (seed {args.seed}) per category, re-run with Claude Code's\n"
                  f"# built-in tools switched off. Generated by runs/make_check_config.py; {len(tasks)} runs.\n")
    out.write_text(header + yaml.safe_dump({"tasks": tasks}, sort_keys=False))
    print(f"wrote {out.relative_to(REPO)} ({len(tasks)} runs)")


if __name__ == "__main__":
    main()
