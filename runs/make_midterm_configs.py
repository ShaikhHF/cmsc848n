"""Write AgentAbstain task lists for the midterm runs.

  midterm_fill.yaml    every missing or crashed side of a pair that already has
                       results, so each started pair ends up with both sides graded
  midterm_sample.yaml  N random pairs (both sides) from each category with no
                       results yet, so the pilot covers all eight categories

Re-run this after a batch finishes: anything that crashed again shows up in
midterm_fill.yaml.

Usage:
    python runs/make_midterm_configs.py [--per-category 4] [--seed 0]
"""

from __future__ import annotations

import argparse
import json
import random
from collections import defaultdict
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
BENCHMARK = REPO / "third_party" / "agentabstain" / "src" / "configs" / "tasks_preview.yaml"
RESULTS = REPO / "agentabstain_results" / "claudesdk"
MODEL_GLOB = "*claude-sonnet-4-6"  # Bedrock and Anthropic API runs of the same model


def graded_sides(results_dir: Path) -> dict[tuple[str, str], set[str]]:
    """(category, task_id) -> sides that have a run without a run error."""
    done: dict = defaultdict(set)
    for eval_path in (p for d in results_dir.glob(MODEL_GLOB) for p in d.rglob("eval.json")):
        ev = json.loads(eval_path.read_text())
        key = (ev["category"], ev["task_id"])
        done.setdefault(key, set())
        if not ev.get("run_error_kind"):
            done[key].add(ev["task_type"])
    return done


def write(path: Path, header: str, tasks: list[dict]) -> None:
    body = yaml.safe_dump({"tasks": tasks}, sort_keys=False)
    path.write_text(f"# {header}\n# Generated by runs/make_midterm_configs.py; {len(tasks)} runs.\n{body}")
    print(f"wrote {path.relative_to(REPO)} ({len(tasks)} runs)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--per-category", type=int, default=4)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    benchmark = yaml.safe_load(BENCHMARK.read_text())["tasks"]
    pairs_by_category: dict = defaultdict(list)
    for t in benchmark:
        if t["task_type"] == "act":
            pairs_by_category[t["category"]].append(t["task_id"])

    done = graded_sides(RESULTS)
    fill = [
        {"category": c, "task_id": t, "task_type": side}
        for (c, t), sides in sorted(done.items())
        for side in ("act", "abstain")
        if side not in sides
    ]
    write(REPO / "runs" / "midterm_fill.yaml",
          "Missing or crashed sides of pairs that already have results.", fill)

    rng = random.Random(args.seed)
    started = {c for c, _ in done}
    sample = []
    for category in sorted(pairs_by_category):
        if category in started:
            continue
        for task_id in sorted(rng.sample(sorted(pairs_by_category[category]), args.per_category)):
            sample += [{"category": category, "task_id": task_id, "task_type": s} for s in ("act", "abstain")]
    write(REPO / "runs" / "midterm_sample.yaml",
          f"{args.per_category} random pairs (seed {args.seed}) from each category with no results yet.",
          sample)


if __name__ == "__main__":
    main()
